"""Replay the new output-side rules on recorded live answers (no model).

    python evaluation/security_replay.py --out ../docs/evidence/2026-10-19-security-replay.md

For every final answer recorded in the 2026-10-19 live runs (development and
held-out), it applies the rules added in the security-hardening work to the
answer exactly as recorded, with the recorded trace:

- LeakGuard (internal instructions / data)                 -> would be blocked
- injected compliance (needs the request's input findings) -> would be revised
- combination claims and confirmed-request claims           -> would be revised
- one internal name in an otherwise normal answer           -> would be reworded
- an answer recorded as grounded=False (returned flagged after its one
  revision under the old rules)                              -> would be replaced

This is a false-positive check on real model output: an answer that passed
its case and would now be changed is a cost of the new rules. It cannot show
what the model would have said after a revision, and it cannot apply the
requested-section rule (old traces have no requested_sections), so those
are reported as limits, not results. Answers are never printed; a blocked
answer is identified by case and run only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent.assistant import INTERNAL_MESSAGES, PROMPT_PATH, TOOL_SPECS  # noqa: E402
from agent.evidence import affirmed_request_claims, combination_claims  # noqa: E402
from agent.security import (  # noqa: E402
    LeakGuard,
    injected_compliance,
    inspect_request,
    protected_texts,
    redact_internal_names,
)

EVIDENCE = ROOT.parent / "docs" / "evidence"


def replay(evidence: Path = EVIDENCE) -> list[dict]:
    guard = LeakGuard(protected_texts(
        PROMPT_PATH.read_text(encoding="utf-8").replace("{term_id}", "2027SP"), TOOL_SPECS, INTERNAL_MESSAGES))
    rows = []
    for f in sorted(evidence.glob("2026-10-19-*/[EH][0-9][0-9].json")):
        saved = json.loads(f.read_text(encoding="utf-8"))
        record, score = saved["record"], saved.get("score", {})
        result = record.get("result")
        if not result:
            continue  # infrastructure error: no answer
        answer, trace, request = result["answer"], result["trace"], record["request"]
        findings = inspect_request(request)
        effects = []
        leak = guard.check(answer)
        if leak:
            effects.append(f"blocked: {leak['kind']}")
        else:
            if injected_compliance(answer, findings):
                effects.append("revise: injected compliance")
            if combination_claims(answer, trace) or affirmed_request_claims(answer, request, trace):
                effects.append("revise: unsupported combination/confirmation")
            if redact_internal_names(answer)[1]:
                effects.append("reword: internal name")
            if result.get("grounded") is False:
                effects.append("replace: returned flagged (grounded=False) under the old rules")
        rows.append({"run": f.parent.name.removeprefix("2026-10-19-"), "case_id": record["case_id"],
                     "passed": score.get("pass"), "effects": effects,
                     "input_flags": [k for k in ("override", "exfiltration", "forged_tool_output",
                                                 "impersonation") if getattr(findings, k)]})
    return rows


def to_markdown(rows: list[dict]) -> str:
    changed = [r for r in rows if r["effects"]]
    passed_changed = [r for r in changed if r["passed"]]
    cases = sorted({r["case_id"] for r in changed})
    lines = [
        "# Replay of the new output rules on recorded live answers",
        "",
        "Generated by `ai-agent/evaluation/security_replay.py` (no model; answers as recorded on 2026-10-19).",
        "",
        f"- Final answers replayed: {len(rows)} (all development and held-out live runs with an answer)",
        f"- Answers the new rules would change: {len(changed)} (cases: {', '.join(cases) or 'none'})",
        f"- Of these, answers that PASSED their case (possible false positives): {len(passed_changed)}"
        + (f" ({', '.join(sorted({r['run'] + '/' + r['case_id'] for r in passed_changed}))})" if passed_changed else ""),
        f"- Requests flagged by input inspection: "
        f"{', '.join(sorted({r['case_id'] for r in rows if r['input_flags']})) or 'none'}",
        "",
        "Limits: a revised answer cannot be replayed (the model is not run), and the requested-section rule",
        "needs `requested_sections`, which these traces predate.",
        "",
        "| Run | Case | Passed when recorded | Effect of the new rules | Input flags |",
        "|---|---|---|---|---|",
    ]
    for r in changed:
        lines.append(f"| {r['run']} | {r['case_id']} | {r['passed']} | {'; '.join(r['effects'])} | "
                     f"{', '.join(r['input_flags']) or '-'} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--out")
    a = p.parse_args()
    rows = replay()
    md = to_markdown(rows)
    print(md)
    if a.out:
        Path(a.out).write_text(md, encoding="utf-8")
        Path(a.out).with_suffix(".json").write_text(json.dumps(rows, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
